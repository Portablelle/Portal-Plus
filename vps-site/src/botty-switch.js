import { sha256 } from './transmission.js';

const ROOT = '/data/botty/emulation/switch';
const encoder = new TextEncoder();
const decoder = new TextDecoder();
const endpoint = '/private/switch/';

function validateInventory(files) {
  if (!Array.isArray(files) || files.length < 2 || files.length > 1024) throw Error('Invalid private Switch inventory.');
  const names = new Set();
  let total = 0;
  for (const file of files) {
    if (!file || typeof file !== 'object' || !/^(keys\/(prod\.keys|title\.keys(?:_autogenerated)?)|firmware\/[a-fA-F0-9]{32}\.nca)$/.test(file.path) ||
        names.has(file.path) || !Number.isSafeInteger(file.size) || file.size < 1 || file.size > 128 * 1024 * 1024 ||
        !/^[a-f0-9]{64}$/.test(file.sha256)) throw Error('Invalid private Switch file.');
    names.add(file.path); total += file.size;
  }
  if (!names.has('keys/prod.keys') || !files.some(f => f.path.startsWith('firmware/')) || total > 1024 * 1024 * 1024)
    throw Error('Incomplete or oversized private Switch runtime.');
}

// The authenticated origin serves the owner's files outside the public app tree.
// No credentials, keys or firmware are part of the static Portal release.
export async function provisionSwitch(io, options = {}) {
  const fetchFile = options.fetchFile || fetch;
  const digest = options.digest || sha256;
  const report = options.report || (() => {});
  const response = await fetchFile(endpoint + 'manifest.json', {cache: 'no-store', credentials: 'same-origin'});
  if (!response.ok) throw Error('Sign in to the private Switch provisioning endpoint, then retry.');
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.length > 1024 * 1024) throw Error('Private Switch manifest is too large.');
  const manifest = JSON.parse(decoder.decode(bytes));
  if (manifest.schema !== 1 || manifest.private !== true || !Array.isArray(manifest.files) ||
      manifest.files.length < 2 || manifest.files.length > 1024) throw Error('Invalid private Switch manifest.');
  validateInventory(manifest.files);
  const manifestHash = await digest(bytes);
  const staging = ROOT + '/.provision/' + manifestHash;
  let completed = 0;
  for (const folder of ['keys', 'firmware']) {
    const group = manifest.files.filter(file => file.path.startsWith(folder + '/'));
    let existing = 0;
    for (const file of group) {
      const previous = await io.readFile(ROOT + '/' + file.path, 128 * 1024 * 1024);
      if (previous) {
        if (previous.length !== file.size || await digest(previous) !== file.sha256)
          throw Error('Existing Switch runtime differs. Your files were preserved.');
        ++existing;
      }
    }
    if (existing && existing !== group.length)
      throw Error('Existing Switch runtime is incomplete. Your files were preserved.');
    if (existing === group.length) { completed += group.length; continue; }
    await io.mkdirs(staging + '/' + folder);
    for (const file of group) {
      const staged = staging + '/' + file.path;
      let data = await io.readFile(staged, 128 * 1024 * 1024);
      if (!data || data.length !== file.size || await digest(data) !== file.sha256) {
        const download = await fetchFile(endpoint + file.path, {cache: 'no-store', credentials: 'same-origin'});
        if (!download.ok) throw Error('Private Switch download unavailable. Retry provisioning.');
        data = new Uint8Array(await download.arrayBuffer());
        if (data.length !== file.size || await digest(data) !== file.sha256) throw Error('Private Switch file verification failed.');
        await io.writeFile(staged, data);
        const disk = await io.readFile(staged, file.size);
        if (!disk || await digest(disk) !== file.sha256) throw Error('Private Switch staging verification failed.');
      }
      report('Preparing Switch runtime: ' + (++completed) + '/' + manifest.files.length);
    }
    await io.publishPrivateDirectory(staging + '/' + folder, ROOT + '/' + folder);
  }
  await io.writeFile(ROOT + '/private-runtime.json', encoder.encode(JSON.stringify({schema: 1, manifest: await digest(bytes), files: manifest.files.length, inventory: manifest.files}) + '\n'));
  report('Private Switch runtime ready.');
}

// A completed private runtime does not require server access on every app launch.
// Explicit refreshes still verify every file against the authenticated manifest.
export async function ensureSwitchRuntime(io, options = {}) {
  const receipt = await io.readFile(ROOT + '/private-runtime.json', 1024 * 1024);
  if (receipt && !options.refresh) {
    try {
      const value = JSON.parse(decoder.decode(receipt));
      validateInventory(value.inventory);
      if (value.schema === 1 && /^[a-f0-9]{64}$/.test(value.manifest) && value.files === value.inventory.length) {
        const digest = options.digest || sha256;
        let intact = true;
        for (const file of value.inventory) {
          const bytes = await io.readFile(ROOT + '/' + file.path, file.size);
          if (!bytes || bytes.length !== file.size || await digest(bytes) !== file.sha256) { intact = false; break; }
        }
        if (intact) return;
      }
    } catch (_) { /* Incomplete receipt/files: use the resumable provisioning path. */ }
  }
  await provisionSwitch(io, options);
}
